#!/usr/bin/env python3
"""Generates UMVC3Hook/code/lobby_font_tables.inc.

The game turns UTF-8 into glyph indices in sGameConfig__mapUtf8GlyphToFontIndex
(see doc/native_lobby_ui.md): ASCII is `codepoint - 0x20`, and every
other character is looked up in one string that lists the glyphs in atlas order
starting at index 0x60. That string is UTF-16 in the executable. Advance widths
are the fonts' .fsd tables (28-byte header, then one uint32 per glyph).

usage: gen_lobby_font_tables.py <umvc3.exe.unpacked.exe> <ui_cache dir> <out.inc>
"""
import struct
import sys

FIRST_TABLE_GLYPH = 0x60
TABLE_START = " ¡¢£™".encode("utf-16le")


def glyph_order(exe):
    at = exe.find(TABLE_START)
    if at < 0 or exe.find(TABLE_START, at + 2) >= 0:
        sys.exit("glyph table not found exactly once")
    end = at
    while exe[end:end + 2] != b"\0\0":
        end += 2
    return exe[at:end].decode("utf-16le")


def widths(path):
    data = open(path, "rb").read()
    magic, _, count = struct.unpack_from("<4sII", data, 0)
    if magic != b"FSD\0" or len(data) != 28 + 4 * count:
        sys.exit("unexpected font metrics: " + path)
    return struct.unpack_from("<%dI" % count, data, 28)


def rows(values, per_line, fmt):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ",".join(fmt % v for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


def main():
    exe_path, cache, out_path = sys.argv[1:4]
    order = glyph_order(open(exe_path, "rb").read())
    # The game searches the string front to back: the first occurrence wins.
    index = {}
    for i, char in enumerate(order):
        index.setdefault(ord(char), FIRST_TABLE_GLYPH + i)
    codepoints = sorted(index)
    if codepoints[-1] > 0xFFFF:
        sys.exit("glyph outside the BMP")
    body = widths(cache + "/nrodinpro_BM_HQ_NOMIP.fsd")
    heading = widths(cache + "/bada_b_BM_HQ_NOMIP.fsd")
    body = body[:FIRST_TABLE_GLYPH + len(order)]

    with open(out_path, "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by tools/gen_lobby_font_tables.py; do not edit.\n")
        out.write("// The game's glyph order beyond ASCII (%d glyphs from index 0x%X),\n"
                  % (len(order), FIRST_TABLE_GLYPH))
        out.write("// as sorted codepoints with their glyph indices, and both fonts'\n")
        out.write("// advance widths by glyph index.\n")
        out.write("constexpr uint16_t kGlyphCodepoints[%d] = {\n%s\n};\n"
                  % (len(codepoints), rows(codepoints, 12, "0x%04X")))
        out.write("constexpr uint16_t kGlyphIndices[%d] = {\n%s\n};\n"
                  % (len(codepoints), rows([index[c] for c in codepoints], 16, "%d")))
        out.write("constexpr uint8_t kBodyWidths[%d] = {\n%s\n};\n"
                  % (len(body), rows(body, 32, "%d")))
        out.write("constexpr uint8_t kHeadingWidths[%d] = {\n%s\n};\n"
                  % (len(heading), rows(heading, 32, "%d")))


if __name__ == "__main__":
    main()
